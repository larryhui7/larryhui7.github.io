def sensing_trace(domain, positions, i, radius):
    """Table I, "Adjust sensing radius" (Sec. IV-B, Fig. 4).

    Agent i finds its own Voronoi cell using only the agents it can detect:

        1. detect all agents within distance R
        2. W = Q  ∩  B(p_i, R)  ∩  half-planes of the detected agents
        3. if R >= 2 max_{q in W} |q - p_i|, W is the true Voronoi cell: stop
        4. otherwise double R and repeat

    Input:  domain, positions, agent index i, starting radius.
    Output: (cell, final_radius, trace). final_radius = 2 max |q - p_i| is the
            smallest radius that certifies the cell. trace has one dict per
            value of R tried, which the radius pages replay step by step.

    The disk B(p_i, R) is cut as a 64-sided polygon that contains it, so the
    test in step 3 can only be stricter than the paper's. Once it passes, W is
    inside B(p_i, R/2) and the disk no longer touches it.
    """
    R = max(float(radius), 1e-4)
    trace = []
    for _ in range(30):
        detected = np.where(np.linalg.norm(positions - positions[i], axis=1) <= R + 1e-10)[0]
        v = cell(domain, positions, i, detected)
        if np.linalg.norm(v - positions[i], axis=1).max() > R/2 + 1e-9:
            for angle in np.linspace(0, 2*np.pi, 64, endpoint=False):
                normal = np.array([np.cos(angle), np.sin(angle)])
                v = clip(v, normal, np.dot(normal, positions[i]) + R)
        reach = np.linalg.norm(v - positions[i], axis=1).max()
        certified = R >= 2*reach - 1e-9
        trace.append({'radius': R, 'reach': float(reach), 'required': float(2*reach),
                      'detected': detected.tolist(), 'cell': v, 'certified': bool(certified)})
        if certified:
            return v, 2*reach, trace
        R *= 2
    raise RuntimeError('Sensing radius did not certify')


def monitor_update(old, new, event=False):
    """Table II, "Monitoring" (Sec. IV-B).

    Each agent stores a weight for every other agent:
        3 = Voronoi neighbor that is moving, 1 = neighbor that is idle, 0 = not a neighbor.
    A jump of +2 or more means a neighbor started moving or a moving agent
    became a neighbor, so the agent's centroid may be out of date.

    Input:  old stored weights, new current weights, event = the current flag.
    Output: (stored, event, triggered). The stored weights are replaced by the
            new ones whenever any weight changed by 2 or more in either
            direction. event stays set until the controller clears it.
            triggered says whether this call raised it.
    """
    old, new = np.asarray(old), np.asarray(new)
    delta = new - old
    changed = bool(np.any(np.abs(delta) >= 2))
    triggered = bool(np.any(delta >= 2))
    return (new if changed else old).copy(), bool(event or triggered), triggered
